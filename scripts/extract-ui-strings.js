/**
 * Pulls interface wording that lives in the pages into the translation catalogue.
 *
 * Most strings are declared in src/shared/i18n.ts with hand-written keys. The
 * Settings page and the new tab page are different: their wording is written
 * inline, hundreds of strings of it, and none of it was reachable by the
 * translation editor — so those pages stayed English no matter what language
 * was chosen.
 *
 * Rather than invent a key for each one by hand, keys are derived from the
 * English text itself, matching `uiKey` in src/shared/i18n.ts. Re-run this after
 * adding or rewording anything user-visible:
 *
 *     node scripts/extract-ui-strings.js
 */

const { readFileSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')

const ROOT = join(__dirname, '..')

/** Settings supplies row()/title:/actionButton(); every file supplies t('…'). */
const SOURCES = [
  'src/renderer/settings.ts',
  'src/renderer/home.ts',
  'src/renderer/bookmarks.ts',
  'src/renderer/translate.ts',
  'src/renderer/main.ts'
]

const OUT = join(ROOT, 'src/shared/i18n-settings.ts')

/** Must stay identical to `uiKey` in src/shared/i18n.ts. */
function uiKey(text) {
  const slug = text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 44)
    .replace(/-$/, '')

  // Two different strings can slug to the same thing once truncated, so the
  // full text decides the suffix.
  let hash = 0
  for (let i = 0; i < text.length; i++) hash = (hash * 31 + text.charCodeAt(i)) >>> 0

  return `ui.${slug}-${hash.toString(36).slice(0, 4)}`
}

const source = SOURCES.map((relative) => readFileSync(join(ROOT, relative), 'utf8')).join('\n')

/** Matches a quoted JS string, honouring backslash escapes. */
const STRING = String.raw`'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"`

function unescape(raw) {
  return raw.replace(/\\(['"\\])/g, '$1').replace(/\\n/g, '\n')
}

const found = new Map()

function add(text) {
  const clean = (text || '').trim()

  // Skip anything that is plainly not prose: identifiers, ids, urls, colours.
  if (!clean || clean.length < 3) return
  if (/^[a-z][a-zA-Z0-9]*$/.test(clean)) return
  if (/^#|^ie2:|^https?:/.test(clean)) return
  if (!/[a-z]/i.test(clean)) return
  // Class names and other single hyphenated tokens.
  if (/^[a-z0-9-]+$/.test(clean) && !clean.includes(' ')) return
  // Catalogue keys, which look like prose to a regex but are not.
  if (/^[a-z]+\.[a-zA-Z]+$/.test(clean)) return

  found.set(uiKey(clean), clean)
}

/** Add the first captured string of every match. */
function scan(pattern) {
  for (const match of source.matchAll(pattern)) {
    for (let i = 1; i < match.length; i++) {
      if (match[i] !== undefined) {
        add(unescape(match[i]))
        break
      }
    }
  }
}

// row('Title', 'Description', control) — both halves of every settings row.
for (const match of source.matchAll(
  new RegExp(String.raw`\brow\(\s*(?:${STRING})\s*,\s*(?:${STRING})`, 'g')
)) {
  add(unescape(match[1] ?? match[2] ?? ''))
  add(unescape(match[3] ?? match[4] ?? ''))
}

// Section headings.
scan(new RegExp(String.raw`\btitle:\s*(?:${STRING})`, 'g'))

// Every button on the Settings page.
scan(new RegExp(String.raw`\bactionButton\(\s*(?:${STRING})`, 'g'))

// t('…') — the general escape hatch. Any string a page writes straight into the
// DOM becomes translatable by wrapping it, with no key to invent.
scan(new RegExp(String.raw`(?<![\w.])t\(\s*(?:${STRING})\s*\)`, 'g'))

// Prose written as bare strings in a table, which is how the About page's
// headings and paragraphs are declared.
scan(new RegExp(String.raw`^\s*(?:${STRING}),?$`, 'gm'))

const entries = [...found].sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([key, text]) => `  '${key}': ${JSON.stringify(text)}`).join(',\n')

writeFileSync(
  OUT,
  `/**
 * Interface wording extracted from the pages that declare it inline — the
 * Settings page, the new tab page, and anything wrapped in \`t('…')\`.
 *
 * Generated by scripts/extract-ui-strings.js — do not edit by hand. Re-run that
 * script after adding or rewording anything, then translate the new keys in the
 * browser's own translation editor.
 */

export const EN_SETTINGS: Record<string, string> = {
${body}
}
`,
  'utf8'
)

console.log(`extracted ${entries.length} interface strings -> src/shared/i18n-settings.ts`)
